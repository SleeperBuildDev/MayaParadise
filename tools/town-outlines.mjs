// Writes js/story/world/regions/outlines.js: each town's OUTLINE (its rects, roads, Bookmark Desks and ground
// style), so the whole land's map, road network and desks exist at boot while a town's heavy part (art, items,
// people) downloads later (js/story/world/townloader.js, ?lazy=1). Also which towns each day's module brings
// with it (its static imports), so those towns are merged at boot instead of fetched twice.
//
//   node tools/town-outlines.mjs           write the file
//   node tools/town-outlines.mjs --check   exit 1 when the file is out of date (a town's rect, roads or desks changed)
//
// Run it after changing a town's REGION, ROAD_NODES, ROAD_EDGES, DESKS or GROUND. The game also warns in the
// console (lazy mode) when a town arrives and its outline differs.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REG = join(ROOT, 'js/story/world/regions');
const OUT = join(REG, 'outlines.js');
const TOWNS = ['quarter', 'market', 'wharf', 'junction', 'hearth', 'garden', 'blank']; // regions/index.js order (home is always loaded)

// town files read the save at import (garden/hearth folk by day, blank's back-cover door): none of that is outline data
globalThis.localStorage ??= { getItem: () => null, setItem() {}, removeItem() {} };

const list = (v) => (v == null ? [] : Array.isArray(v) ? v : [v]);
const round = (v) => (typeof v === 'number' ? Math.round(v * 1e4) / 1e4 : v);
function plain(v) {
  if (Array.isArray(v)) return v.map(plain);
  if (v && typeof v === 'object') { const o = {}; for (const [k, x] of Object.entries(v)) if (typeof x !== 'function' && x !== undefined) o[k] = plain(x); return o; }
  return round(v);
}

const towns = {};
for (const t of TOWNS) {
  const m = await import(pathToFileURL(join(REG, `${t}.js`)).href);
  const regs = list(m.REGION);
  towns[t] = {
    regions: regs.map((r) => r.id),
    REGION: plain(regs),
    ROAD_NODES: plain(list(m.ROAD_NODES)),
    ROAD_EDGES: plain(list(m.ROAD_EDGES)),
    DESKS: plain(list(m.DESKS)),
    ...(m.GROUND ? { GROUND: plain(m.GROUND) } : {}),
  };
}

// which towns each day's module imports statically (they download with the day, so the boot merges them)
const STORY = join(ROOT, 'js/story');
const IMPORT_RE = /^\s*(?:import|export)\s[^'"`;]*?from\s*['"]([^'"]+)['"]|^\s*import\s*['"]([^'"]+)['"]/gm;
const strip = (s) => s.replace(/^\s*\/\/.*$/gm, ''); // (full-line comments only: a comment may say rooms/*.js)
function townsOf(file, seen = new Set()) {
  const out = new Set();
  if (seen.has(file) || !existsSync(file)) return out;
  seen.add(file);
  const src = strip(readFileSync(file, 'utf8'));
  for (const mm of src.matchAll(IMPORT_RE)) {
    const spec = (mm[1] || mm[2] || '').split('?')[0];
    if (!spec.startsWith('.')) continue;
    const f = resolve(dirname(file), spec);
    const rel = relative(REG, f).replace(/\\/g, '/');
    const hit = /^([a-z]+)\.js$/.exec(rel);
    if (hit && TOWNS.includes(hit[1])) { out.add(hit[1]); continue; }
    if (!rel.startsWith('..') ) continue; // (a town's own parts)
    if (f.endsWith('region.js') || f.endsWith(join('regions', 'index.js'))) continue;
    for (const x of townsOf(f, seen)) out.add(x);
  }
  return out;
}
const DAY_IMPORTS = {};
for (let n = 1; n <= 15; n++) {
  const f = join(STORY, `day${n}.js`);
  DAY_IMPORTS[n] = existsSync(f) ? TOWNS.filter((t) => townsOf(f).has(t)) : [];
}

// each town's own files (its static import graph inside regions/ and art/; kit.js and the game's modules are core)
const ART = join(ROOT, 'js/story/world/art');
function filesOf(file, out = new Set()) {
  if (out.has(file) || !existsSync(file)) return out;
  out.add(file);
  for (const mm of strip(readFileSync(file, 'utf8')).matchAll(IMPORT_RE)) {
    const spec = (mm[1] || mm[2] || '').split('?')[0];
    if (!spec.startsWith('.')) continue;
    const f = resolve(dirname(file), spec);
    if (dirname(f) === REG || dirname(f) === ART) filesOf(f, out);
  }
  return out;
}
const FILES = {};
for (const t of TOWNS) FILES[t] = [...filesOf(join(REG, `${t}.js`))].map((f) => relative(ROOT, f).split('\\').join('/')).sort();

const body = `// GENERATED by tools/town-outlines.mjs from regions/<town>.js. Do not edit: run \`node tools/town-outlines.mjs\`
// after changing a town's REGION, ROAD_NODES, ROAD_EDGES, DESKS or GROUND. Used only by the lazy town loader
// (region.js, ?lazy=1): the whole land's outline at boot, each town's heavy part (art, items, people) later.
export const TOWNS = ${JSON.stringify(towns)};
/** Towns each day's module imports statically (they arrive with the day). */
export const DAY_IMPORTS = ${JSON.stringify(DAY_IMPORTS)};
/** Each town's own files (site-root paths): fetched together, then imported (one round trip, not a chain). */
export const FILES = ${JSON.stringify(FILES)};
`;
if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== body) { console.error('outlines.js is out of date: run node tools/town-outlines.mjs'); process.exit(1); }
  console.log('outlines.js is up to date');
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${relative(ROOT, OUT)} (${body.length} bytes)`, DAY_IMPORTS);
}
