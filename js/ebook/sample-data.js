const MM_DIGITS = ['၀', '၁', '၂', '၃', '၄', '၅', '၆', '၇', '၈', '၉'];

function toMyanmarDigits(value) {
  return String(value).replace(/[0-9]/g, (d) => MM_DIGITS[Number(d)]);
}

